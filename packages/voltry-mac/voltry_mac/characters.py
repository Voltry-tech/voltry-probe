def _groups(text: str, size: int) -> list[tuple[int, ...]]:
    numbers = [int(token, 16) for token in text.split()]
    return [tuple(numbers[index : index + size]) for index in range(0, len(numbers), size)]


def _mapping(text: str) -> dict[str, str]:
    """Each "c0:41.300" as the character U+00C0 and the text "A" and U+0300."""
    found = {}
    for group in text.split():
        key, _, value = group.partition(":")
        found[chr(int(key, 16))] = "".join(chr(int(point, 16)) for point in value.split("."))
    return found


