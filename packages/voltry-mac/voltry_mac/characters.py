"""What a character is, as the renderers need to know it: a static table of Unicode 15.0.0.

docs/VOLTRY_MAC_SPEC.md, Decision 4 (another Python reproduces the same content, and a
character outside WinAnsi is replaced and counted in Appendix B) and the Architecture's
renderers row (control characters from system output are stripped before printing; the
display path escapes what would hide and prints the home folder as ~). The terminal and
the PDF take a character's general category, its width, what it composes to and how a name
folds from this table, never from the running Python's unicodedata or str methods, whose
Unicode version is not the same on the Pythons the package supports (14.0.0 on 3.11,
15.0.0 on 3.12, 16.0.0 on 3.14), so each of them prints a report alike. The table is the
database of the Python the repository pins (3.12): tests/character_table.py writes it, and
a test compares the two whenever the running Python's database is the table's version.
Pure: lookups in runs of code points and in mappings.
"""

from __future__ import annotations

import bisect
from typing import Final


def category(character: str) -> str | None:
    """The character's general category, when it is one the renderers act on: a control, a
    format character or a separator (Cc, Cf, Zl, Zp, Zs), a mark (Mn, Mc, Me), or a
    surrogate, private-use or unassigned code point (Cs, Co, Cn). None for any other: a
    letter, a number, punctuation or a symbol."""
    return _NAMES[bisect.bisect_right(_STARTS, ord(character)) - 1]


def wide(character: str) -> bool:
    """Whether the character takes two terminal columns: East Asian Width W or F."""
    return bisect.bisect_right(_BOUNDS, ord(character)) % 2 == 1


def composed(text: str) -> str:
    """text with what composes to one WinAnsi character composed, in one pass from the
    left, as NFC composes it: a letter and the combining mark right after it ("e" and
    U+0301 COMBINING ACUTE ACCENT, U+00E9), and a character canonically equivalent to one
    (U+212A KELVIN SIGN, "K"). Every other character stays as it is, for the PDF to print
    as itself or as a counted "?".

    Marks are never reordered, and only the mark right after a letter composes with it, so
    a second mark stays as it is: "e", U+0301 and U+0323 give U+00E9 and U+0323. NFC would
    first sort the marks by their combining classes, which could compose another pair
    instead (U+1EB9 and the acute left over) or compose across a mark (a c with a cedilla
    and an acute is U+1E09). This sorts nothing, so the pairs alone decide what prints."""
    if _COMPOSING.isdisjoint(text):
        return text
    out, index = [], 0
    while index < len(text):
        pair = _PAIRS_BY_TEXT.get(text[index : index + 2])
        if pair is None:
            out.append(_SINGLES_BY_CHARACTER.get(text[index], text[index]))
            index += 1
        else:
            out.append(pair)
            index += 2
    return "".join(out)


def folded(text: str) -> str:
    """text as the default APFS volume compares a name, keeping neither case nor Unicode
    normalization apart: decomposed (NFD), folded by Unicode's full case folding, and
    decomposed again, by the table alone. It is what Python 3.12 gives for
    unicodedata.normalize("NFD", unicodedata.normalize("NFD", text).casefold()); the
    Pythons before and after it fold some characters otherwise (U+A7CB, a capital Unicode
    16.0.0 added, folds on 3.14 and is unassigned here)."""
    return _decomposed("".join(_FOLDINGS_BY_CHARACTER.get(c, c) for c in _decomposed(text)))


def _decomposed(text: str) -> str:
    """NFD by the table: each character as its canonical decomposition, a Hangul syllable's
    by the Unicode Standard's algorithm (section 3.12), then each run of marks in the order
    of their combining classes, marks of one class kept in their order (UAX #15)."""
    points: list[str] = []
    for character in text:
        syllable = ord(character) - _SYLLABLE
        if 0 <= syllable < _SYLLABLES:
            lead, rest = divmod(syllable, _VOWELS * _TAILS)
            vowel, tail = divmod(rest, _TAILS)
            points += [chr(_LEAD + lead), chr(_VOWEL + vowel)]
            if tail:
                points.append(chr(_TAIL + tail))
        else:
            points += _DECOMPOSITIONS_BY_CHARACTER.get(character, character)
    start = 0
    while start < len(points):
        end = start
        while end < len(points) and _combining(points[end]):
            end += 1
        if end > start + 1:
            points[start:end] = sorted(points[start:end], key=_combining)
        start = end + 1
    return "".join(points)


def _combining(character: str) -> int:
    """The character's canonical combining class: 0 for a starter."""
    return _CLASS_VALUES[bisect.bisect_right(_CLASS_STARTS, ord(character)) - 1]


